# ------------------------------------------------------------------ diagnostics
def scaling_report(alpha, ns=(10, 100, 1000)):
    """How each of the eight quantities scales in n at a fixed alpha."""
    print("  quantity        " + "".join(f"{n:>14d}" for n in ns) + "    exponent")
    vals = {nm: [] for nm in NAMES}
    for n in ns:
        for nm, v in hard_at(alpha, n):
            vals[nm].append(float(v))
    for nm in NAMES:
        v = vals[nm]
        e = None
        if v[0] and v[-1] and v[0] * v[-1] > 0:
            e = np.log(abs(v[-1] / v[0])) / np.log(ns[-1] / ns[0])
        print(f"  {nm:<14s}" + "".join(f"{x:14.4e}" for x in v)
              + (f"    n^{e:+.2f}" if e is not None else "    (sign change)"))
    return vals


# ------------------------------------------------------------------- the SDP
def sbasis(n, D):
    """
    The ansatz basis.  Put s = m/n = 1 - 4/n, which runs over [0, 1) as n runs
    over [4, infinity), and take

        f_c = ( sum_j w_j s^j ) / n^3 .

    This spans exactly the same functions as u_c(m)/n^{D+3} with deg u_c <= D
    (the change of basis is triangular), but the coefficients are O(1) and the
    variable is bounded, so the fit is well conditioned.  Keeping E = D + 3 is
    what preserves the measured leading order f_c ~ const/n^3; letting E and D
    move independently changes the asymptotics and makes the fit chase the wrong
    limit.
    """
    s = 1.0 - 4.0 / float(n)
    return np.array([s ** j for j in range(D + 1)]) / float(n) ** 3


def solve_alpha(ns, D=0, cap=1e6, verbose=True, E=None, scales=None):
    """
    Maximise the least normalised margin over one curve valid at every n in ns.
    """
    import cvxpy as cp
    u = cp.Variable((4, D + 1))
    t = cp.Variable()
    cons = [t <= cap]
    for n in ns:
        s = 1.0 - 4.0 / float(n)
        b = u @ np.array([s ** j for j in range(D + 1)])     # beta = f * n^3
        q1, q2, qB, qD, Cm, Tm = rd.normalised_forms_exact(n, b)
        cons += [q1 >= t, q2 >= t, qB >= t, qD >= t,
                 Cm - t * np.eye(2) >> 0, Tm - t * np.eye(2) >> 0]
    prob = cp.Problem(cp.Maximize(t), cons)
    for solver in ("CLARABEL", "SCS"):
        try:
            prob.solve(solver=getattr(cp, solver), verbose=False)
            if prob.status in ("optimal", "optimal_inaccurate"):
                if verbose:
                    print(f"    D={D}: {prob.status}, t = {t.value:.6g}")
                return np.array(u.value, dtype=float).reshape(4, D + 1), \
                    float(t.value)
        except Exception as exc:                                 # noqa: BLE001
            if verbose:
                print(f"    {solver} failed: {exc}")
    return None, None


def solve_alpha_ref(ns, D, refs, cap=10.0, verbose=False):
    """
    One curve for every n in ns, with the margin measured RELATIVE to the
    analytic centre at that same n.  t = 1 would mean the curve is as well
    centred as the centre itself; t > 0 means strictly feasible.
    """
    import cvxpy as cp
    u = cp.Variable((4, D + 1))
    t = cp.Variable()
    cons = [t <= cap]
    for n in ns:
        s = 1.0 - 4.0 / float(n)
        b = u @ np.array([s ** j for j in range(D + 1)])
        q1, q2, qB, qD, Cm, Tm = rd.normalised_forms_exact(n, b)
        r = refs[n]
        cons += [q1 >= t * r["q1"], q2 >= t * r["q2"],
                 qB >= t * r["qB"], qD >= t * r["qD"],
                 Cm - t * r["C"] >> 0, Tm - t * r["T"] >> 0]
    prob = cp.Problem(cp.Maximize(t), cons)
    for solver in ("CLARABEL", "SCS"):
        try:
            prob.solve(solver=getattr(cp, solver), verbose=False)
            if prob.status in ("optimal", "optimal_inaccurate"):
                return np.array(u.value, dtype=float).reshape(4, D + 1), \
                    float(t.value)
        except Exception:                                        # noqa: BLE001
            continue
    return None, None


def rf_free_from_s(wq, D):
    """
    The eight free variables over Q(n) from exact coefficients in the s basis:
    f_c = (sum_j w_j s^j)/n^3 with s = (n-4)/n, so f_c = (sum_j w_j (n-4)^j
    n^{D-j}) / n^{D+3}.
    """
    fs = [g.RF([]) for _ in range(NFREE)]
    den = g.RF([F(0)] * (D + 3) + [F(1)])
    for t, i in enumerate(ESS_I):
        num = []
        for j in range(D + 1):
            if not wq[t][j]:
                continue
            acc = [F(1)]
            for _ in range(j):
                acc = g.pmul(acc, [F(-4), F(1)])          # (n-4)^j
            for _ in range(D - j):
                acc = g.pmul(acc, [F(0), F(1)])           # n^{D-j}
            num = g.padd(num, g.pscale(acc, wq[t][j]))
        fs[i] = g.RF(num) / den
    return fs


# ------------------------------------------------------- the gauge, in closed form
RFONE = g.RF([F(1)])
RFN = g.RF([F(0), F(1)])
LIN = None


def _lineality():
    global LIN
    if LIN is None:
        import recession as rc
        LIN = rc.lineality_free()
    return LIN


def rf_free_from_alpha(uq, E):
    """
    The eight free variables as elements of Q(n), from polynomial numerators uq
    (in m = n - 4) for the four ESSENTIAL coordinates.  Gauge coordinates zero.
    """
    nE = g.RF([F(0)] * E + [F(1)])
    fs = [g.RF([]) for _ in range(NFREE)]
    for t, i in enumerate(ESS_I):
        num, acc = [], [F(1)]
        for j, co in enumerate(uq[t]):
            if j:
                acc = g.pmul(acc, [F(-4), F(1)])
            num = g.padd(num, g.pscale(acc, co))
        fs[i] = g.RF(num) / nE
    return fs


def vals19_rf(fs):
    vals = [None] * 19
    for t, c in enumerate(FREE):
        vals[c] = fs[t]
    for i, c in enumerate(fc.PIV):
        v = fc.RES["b"][i]
        for t, fcol in enumerate(FREE):
            a = fc.RES["A"][i][fcol]
            if a:
                v = v - a * fs[t]
        vals[c] = v
    return vals


def apply_gauge(fs, gamma, tau):
    """
    Add the lineality combination that sets theta_0 = tau and makes the 3x3 A
    block equal diag(gamma, T^T A T) in the basis (e, T), e = (1,0,0).

    Both are pure gauge: the eight essential quantities are unchanged, so this
    step cannot fail and introduces no new positivity requirement.  A > 0 then
    holds exactly when T^T A T > 0, which is already one of the eight.
    """
    vals = vals19_rf(fs)
    a, b, c = vals[0], vals[1], vals[2]
    m = RFN - RFONE
    theta0 = a + b * (RFONE + RFONE) * m + c * m * m
    A, _, _, _ = bl.blocks_rational_generic(RFN, vals[3:14], IDX, one=RFONE)

    two = RFONE + RFONE
    p1 = A[0][1] - A[0][0] * two * m
    p2 = A[0][2] - A[0][0] * m * m
    w1 = (gamma - A[0][0]) / two
    w2 = (g.RF([]) - p1) + w1 * two * m
    w3 = (g.RF([]) - p2) + w1 * m * m
    vK, vR, vI = w1, w2 / (two * m), w3 / (m * m)
    mu = (tau - theta0) / (RFN * RFN)

    L = _lineality()
    out = list(fs)
    for coef, gen in zip((mu, vK, vR, vI), L):
        for t in range(NFREE):
            if gen[t]:
                out[t] = out[t] + coef * gen[t]
    return out


def build(uq, E, gamma=None, tau=None):
    """The full eight free variables over Q(n): essential part plus gauge."""
    gamma = gamma if gamma is not None else RFONE / (RFN * RFN * RFN)
    tau = tau if tau is not None else RFONE / RFN
    return apply_gauge(rf_free_from_alpha(uq, E), gamma, tau)


def build_s(wq, D, gamma=None, tau=None):
    """Same, from exact coefficients in the s = (n-4)/n basis."""
    gamma = gamma if gamma is not None else RFONE / (RFN * RFN * RFN)
    tau = tau if tau is not None else RFONE / RFN
    return apply_gauge(rf_free_from_s(wq, D), gamma, tau)


# ------------------------------------------------------------------- driver
def sturm_report(fs, verbose=True):
    import sturm
    qs = sturm.quantities_rf_from(fs)
    good, bad = [], []
    for name, rf in qs:
        s = sturm.sign_on_n_ge_4(rf.den)
        if s == 0:
            bad.append((name, "denominator not sign-definite"))
            continue
        ok, detail = sturm.positive_on_nonneg(
            sturm.shift_to_m(g.pscale(rf.num, F(s))))
        (good if ok else bad).append((name, detail))
    if verbose:
        for name, detail in good:
            print(f"    POSITIVE  {name:<12s}  {detail}")
        for name, detail in bad:
            print(f"    FAILS     {name:<12s}  {detail}")
    return good, bad


def exact_check(fs, ns):
    bad = []
    for n in ns:
        fv = [f.at(F(n)) for f in fs]
        for nm, v in fc.exact_quantities(n, fv):
            if v <= 0:
                bad.append((n, nm, v))
    return bad


