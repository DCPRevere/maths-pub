"""
The design step on the ESSENTIAL 4-dimensional quotient.

recession.py establishes, exactly over Q(n), that the design problem carries a
FOUR-dimensional lineality space -- generated by sigma_0 Gram += mu J and
sigma_11 Gram += 1 v^T + v 1^T for v constant on the three Stab((0,0)) classes
K, R u C, I -- and that its four generators have an invertible 4 x 4 minor on the
four free lambda columns f15, f16, f17, f18.  So

    {f15 = f16 = f17 = f18 = 0}

is a transversal slice, and the design has only FOUR essential unknowns:
f6, f9, f11, f12.  On that slice the feasible set has trivial recession cone,
hence is COMPACT, which is exactly what the drifting optima of design_sdp.py
lacked.

The eight quantities that live on the quotient are

    theta_1, theta_2, B, D, the two leading minors of C,
    and the two leading minors of T^T A T,   T spanning s^perp,
    s = (1, 2(n-1), (n-1)^2).

The remaining two conditions, theta_0 > 0 and A > 0, are NOT constraints at all:
they are fixed afterwards by the gauge, in closed form.  Write e = (1,0,0), which
satisfies s^T e = 1.  Moving along the lineality space adds mu n^2 to theta_0 and
s w^T + w s^T to A, with w free in R^3; in the basis (e, T) that added matrix is
[[2 w_1, (T^T w)^T], [T^T w, 0]].  So choosing

    T^T w = -T^T A e ,      w_1 = (gamma - A_11)/2 ,      mu = (tau - theta_0)/n^2

makes A block-diagonal, equal to diag(gamma, T^T A T) in the basis (e, T), and
sets theta_0 = tau.  Take gamma = tau = 1.  Then A > 0 exactly when T^T A T > 0,
which is already one of the eight, and theta_0 = 1 > 0.

So the whole k = 3 design reduces to four rational functions of n making eight
explicit rational functions of n positive on n >= 4 -- and the gauge, which is a
formula, supplies the rest.
"""

